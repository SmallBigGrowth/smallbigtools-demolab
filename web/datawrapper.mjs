import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 2, recordVideo: { dir: 'vid', size: { width: 860, height: 1864 } } });
const p = await ctx.newPage();
const pause = (ms) => p.waitForTimeout(ms);
await p.goto('https://app.datawrapper.de/create/chart', { waitUntil: 'networkidle', timeout: 60000 });
await pause(800);
await p.getByRole('button', { name: 'Reject non-essential' }).click().catch(()=>{});
await pause(800);
const sel = p.locator('select').first();
const opts = await sel.locator('option').allTextContents(); console.log('examples:', opts.slice(0,8));
await sel.scrollIntoViewIfNeeded(); await pause(600);
await sel.selectOption({ index: 1 }); await pause(1500);
await p.getByRole('button', { name: 'Proceed' }).first().click(); await p.waitForLoadState('networkidle'); await pause(2000);
console.log('step2', p.url()); await p.screenshot({ path: 's2.png' });
await p.getByRole('button', { name: /Proceed/ }).first().click().catch(e=>console.log('p2',e.message)); await p.waitForLoadState('networkidle'); await pause(3500);
console.log('step3', p.url()); await p.screenshot({ path: 's3.png' });
await p.mouse.wheel(0, 900); await pause(2000); await p.screenshot({ path: 's3b.png' });
await ctx.close(); await b.close();
